"""Vendor the Forever-only library from an official ProfessionDB release ZIP.

Download the archive from its CurseForge release page, review the changelog,
then supply its SHA-256 explicitly. This script never fetches or executes code.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
import shutil
from tempfile import TemporaryDirectory
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / 'vendor/ProfessionDB'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def vendor(archive, version, file_id, sha256, destination=VENDOR):
    archive = Path(archive)
    if digest(archive.read_bytes()) != sha256:
        raise ValueError('Release ZIP SHA-256 does not match the reviewed archive')
    with ZipFile(archive) as release:
        prefix = 'ProfessionDB/'
        toc = release.read(prefix + 'ProfessionDB_Camelot.toc').decode('utf-8-sig')
        metadata = dict(line[3:].split(': ', 1) for line in toc.splitlines() if line.startswith('## '))
        if metadata.get('Version') != 'ProfessionDB-' + version or metadata.get('Interface') != '16001':
            raise ValueError('Unexpected release version or Forever interface; review importer first')
        paths = [line.strip().replace('\\', '/') for line in toc.splitlines()
                 if line.strip() and not line.startswith('#')]
        selected = ['libs/LibStub/LibStub.lua', 'LibProfessionDB-1.0.lua', 'LICENSE']
        selected += [path for path in paths if path.startswith('Data/Forever/') and path.endswith('.lua')]
        if not selected[3:] or any('..' in path.split('/') for path in selected):
            raise ValueError('Missing or invalid Forever payload')
        source = {path: release.read(prefix + path) for path in selected}
    license_text = source['LICENSE'].decode()
    if 'MIT License' not in license_text or 'Copyright (c) 2026 Pimptasty' not in license_text:
        raise ValueError('Upstream license changed; review before redistributing')
    output = {path: data for path, data in source.items() if not path.startswith('Data/Forever/')}
    locales = {}
    for path, data in source.items():
        if path.startswith('Data/Forever/_core/'):
            output[path] = data
        elif path.startswith('Data/Forever/'):
            locale = path.split('/')[2]
            locales.setdefault(locale, []).append((path, data))
    # Combine each locale's original chunks, retaining order and byte content.
    # Each do/end block preserves its local variables and locale-guard return.
    for locale, chunks in locales.items():
        combined = b'-- Generated by scripts/update_profession_db.py; do not hand-edit.\n'
        for path, data in chunks:
            combined += ('\n-- Upstream: ' + path + '\ndo\n').encode() + data + b'\nend\n'
        output['Data/Forever/' + locale + '.lua'] = combined
    loaded = ['libs/LibStub/LibStub.lua', 'LibProfessionDB-1.0.lua']
    loaded += [path for path in output if path.startswith('Data/Forever/_core/')]
    loaded += ['Data/Forever/' + locale + '.lua' for locale in locales]
    builds = {match.group(1) for path, data in source.items() if '/_core/' in path
              for match in [re.search(r'-- build ([\d.]+)', data.decode())] if match}
    minor = re.search(r'local MAJOR, MINOR = "LibProfessionDB-1.0", (\d+)',
                      source['LibProfessionDB-1.0.lua'].decode())
    if len(builds) != 1 or minor is None:
        raise ValueError('Cannot identify upstream client build or API version')
    lock = {
        'project': 'LibProfessionDB', 'version': version, 'curseforge_file_id': file_id,
        'source_url': f'https://www.curseforge.com/wow/addons/libprofessiondb/files/{file_id}',
        'archive_sha256': sha256, 'client_data_build': builds.pop(),
        'interface': 16001, 'library_minor': int(minor.group(1)),
        'note': 'Forever client recipe data; borrowed Vanilla sources retain upstream flags. No rate data.',
        'upstream_files': {path: digest(data) for path, data in source.items()},
        'files': {path: digest(data) for path, data in output.items()},
        'load_order': loaded,
    }
    output['manifest.json'] = (json.dumps(lock, indent=2) + '\n').encode()
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with TemporaryDirectory(dir=destination.parent) as temporary:
        stage = Path(temporary) / 'ProfessionDB'
        for path, data in output.items():
            target = stage / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        if destination.exists():
            shutil.rmtree(destination)
        shutil.move(str(stage), destination)
    return lock


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', required=True, type=Path)
    parser.add_argument('--version', required=True)
    parser.add_argument('--file-id', required=True, type=int)
    parser.add_argument('--sha256', required=True)
    args = parser.parse_args()
    lock = vendor(args.archive, args.version, args.file_id, args.sha256)
    print(f"Vendored {lock['version']}: {len(lock['load_order'])} runtime files")
